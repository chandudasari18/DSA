
/*Print numbers from 1 to 10 using a  loop.
*/

package codegnan.Loops;
import java.util.*;
public class numbers {
public static void main(String args[]) {
	Scanner sc = new Scanner(System.in);
	System.out.print("Enter the n : ");
	int n = sc.nextInt();
	for(int i=0;i<=n;i++) {
		
		System.out.println(i);
	}
 }
}
